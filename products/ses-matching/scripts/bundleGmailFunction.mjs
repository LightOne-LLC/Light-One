// Run this before deploying to Vercel: `npm run build:gmail-function`.
// Local `npm run build`/`npm run dev`/tests never call this — it exists
// solely to produce api/gmail/fetch-one.js before `vercel deploy`/
// `vercel --prod` uploads the working directory.
//
// Why this can't just be Vercel's own build step: `vercel deploy` (CLI)
// uploads the local working directory as-is and decides which api/**
// files are functions from THAT snapshot, before running any build
// command — a file only created *during* the build (e.g. from a
// `vercel-build` script) is never picked up as a function. So the
// bundle has to exist on disk before you invoke the CLI, not be
// generated by it. (A `vercel-build` script was tried first; besides
// this ordering problem, Vercel also runs the build command more than
// once per deployment, and a version of this script that overwrote its
// own entry point in place got bundled on the first pass, then had
// `tsc -b` fail strict type-checking against that now-untyped bundled
// output on the second — reading from a stable source and writing to a
// separate output avoids that too.)
//
// src/server/vercelGmailHandler.ts imports src/server/gmailImportApi.ts,
// which in turn reaches into src/gmail, src/parser, src/intake,
// src/matching, src/demo — code that lives outside api/. This project
// runs as native ESM ("type": "module"), and Vercel's Node Function
// runtime resolves relative imports the way plain Node does: it
// requires an explicit file extension, which our source intentionally
// omits everywhere else (Vite/vitest both resolve extensionless
// specifiers, which is why nothing else needed to change). Rather than
// adding .js extensions across ~25 unrelated existing files just to
// satisfy one deploy target, this script bundles the one Vercel entry
// point into a single self-contained file (third-party packages left
// external — Vercel installs those via package.json as normal).
//
// The output (api/gmail/fetch-one.js) is gitignored, same idea as
// dist/ — api/ has no committed source of its own.
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const entry = path.join(here, '..', 'src', 'server', 'vercelGmailHandler.ts');
const outfile = path.join(here, '..', 'api', 'gmail', 'fetch-one.js');

await build({
  entryPoints: [entry],
  outfile,
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  packages: 'external',
});

console.log(`[bundleGmailFunction] bundled ${entry} -> ${outfile}`);
